import CryptoKit
import Foundation

public struct ArchitectureContextBudget: Codable, Equatable, Sendable {
  public var maximumCards: Int
  public var maximumSourcesPerCard: Int
  public var maximumCardBytes: Int
  public var maximumSourceBytes: Int
  public var maximumIndexBytes: Int

  public init(maximumCards: Int = 12, maximumSourcesPerCard: Int = 12,
              maximumCardBytes: Int = 8_192, maximumSourceBytes: Int = 1_048_576,
              maximumIndexBytes: Int = 8_000) {
    self.maximumCards = min(64, max(1, maximumCards))
    self.maximumSourcesPerCard = min(64, max(1, maximumSourcesPerCard))
    self.maximumCardBytes = min(65_536, max(256, maximumCardBytes))
    self.maximumSourceBytes = min(4_194_304, max(1, maximumSourceBytes))
    self.maximumIndexBytes = min(65_536, max(1_024, maximumIndexBytes))
  }
}

public struct ArchitectureContextReport: Sendable {
  public let indexURL: URL
  public let stateURL: URL
  public let cardURLs: [URL]
  public let cardCount: Int
  public let sourceCount: Int
  public let truncated: Bool
}

public enum ArchitectureContextError: Error, LocalizedError {
  case unsafeDirectory(String)
  case outputConflict(String)

  public var errorDescription: String? {
    switch self {
    case .unsafeDirectory(let path): "Architecture directory is unavailable or unsafe: \(path)"
    case .outputConflict(let path): "Preserving an existing authored or unsafe file: \(path)"
    }
  }
}

/// Explicit local indexing only. This service never invokes a provider or
/// invents summaries, and a matching checksum never attests semantic accuracy.
public enum ArchitectureContextService {
  private static let generator = "ecc-focus-queue.architecture-context.v1"
  private static let indexMarker = "<!-- Generated by ECC Focus Queue architecture-context; do not edit. -->"
  private static let cardMarker = "<!-- fq-architecture: "
  private static let excluded = Set([
    "vendor", "node_modules", "build", "dist", "target", "deriveddata", "generated",
    "pods", "carthage", "venv", "secrets", "credentials", "coverage",
  ])
  private static let sourceExtensions = Set([
    "swift", "py", "js", "ts", "tsx", "jsx", "rs", "go", "java", "kt", "kts",
    "c", "cpp", "h", "m", "mm", "sh", "toml", "sql",
  ])

  private struct Source: Codable {
    let path: String
    let sha256: String?
  }
  private struct CardMetadata: Codable {
    let id: String
    let title: String
    let sources: [Source]
  }
  private struct SourceState: Codable {
    let path: String
    let baselineSHA256: String?
    let currentSHA256: String?
    let status: String
  }
  private struct CardState: Codable {
    let id: String
    let title: String
    let file: String
    let summary: String
    let status: String
    let sources: [SourceState]
  }
  private struct State: Codable {
    let generator: String
    let repositoryRoot: String
    let semanticVerification: String
    let budget: ArchitectureContextBudget
    let truncated: Bool
    let skipped: [String]
    let cards: [CardState]
  }

  public static func generate(repositoryRoot: URL, outputDirectory: URL,
                              cardDirectory: URL? = nil,
                              budget: ArchitectureContextBudget = .init()) throws -> ArchitectureContextReport {
    let budget = ArchitectureContextBudget(maximumCards: budget.maximumCards,
      maximumSourcesPerCard: budget.maximumSourcesPerCard, maximumCardBytes: budget.maximumCardBytes,
      maximumSourceBytes: budget.maximumSourceBytes, maximumIndexBytes: budget.maximumIndexBytes)
    let files = FileManager.default
    let repository = repositoryRoot.standardizedFileURL.resolvingSymlinksInPath()
    guard isDirectory(repository) else { throw ArchitectureContextError.unsafeDirectory(repository.path) }
    let cardRoot = (cardDirectory ?? repository.appendingPathComponent("Docs/Architecture")).standardizedFileURL
    guard safeDescendant(cardRoot, of: repository, allowMissing: true),
      allowedComponents(Array(cardRoot.pathComponents.dropFirst(repository.pathComponents.count))) else {
      throw ArchitectureContextError.unsafeDirectory(cardRoot.path)
    }
    let output = outputDirectory.standardizedFileURL
    if files.fileExists(atPath: output.path), !isDirectory(output) {
      throw ArchitectureContextError.unsafeDirectory(output.path)
    }
    let indexURL = output.appendingPathComponent("architecture-index.generated.md")
    let stateURL = output.appendingPathComponent("architecture-state.generated.json")
    try validateOutput(indexURL, isIndex: true)
    try validateOutput(stateURL, isIndex: false)

    let entries = ((try? files.contentsOfDirectory(at: cardRoot, includingPropertiesForKeys: nil)) ?? [])
      .filter { $0.pathExtension.lowercased() == "md" && !$0.lastPathComponent.contains(".generated.") }
      .sorted { $0.lastPathComponent < $1.lastPathComponent }
    var cards: [CardState] = []
    var cardURLs: [URL] = []
    var skipped: [String] = []
    var truncated = false
    var seenIDs = Set<String>()
    for file in entries {
      guard cards.count < budget.maximumCards else { truncated = true; break }
      guard allowedComponents([file.lastPathComponent]), safeDescendant(file, of: repository),
        let data = boundedData(file, maximumBytes: budget.maximumCardBytes),
        let markdown = String(data: data, encoding: .utf8) else {
        if let attributes = try? files.attributesOfItem(atPath: file.path),
          let size = attributes[.size] as? NSNumber, size.intValue > budget.maximumCardBytes { truncated = true }
        skipped.append("\(file.lastPathComponent): unreadable, unsafe, or over card budget")
        continue
      }
      guard let first = markdown.components(separatedBy: .newlines).first,
        first.hasPrefix(cardMarker), first.hasSuffix(" -->") else { continue }
      let payload = String(first.dropFirst(cardMarker.count).dropLast(4))
      guard let metadata = try? JSONDecoder().decode(CardMetadata.self, from: Data(payload.utf8)),
        metadata.id.range(of: #"^[a-z0-9][a-z0-9-]{0,63}$"#, options: .regularExpression) != nil,
        seenIDs.insert(metadata.id).inserted else {
        skipped.append("\(file.lastPathComponent): invalid metadata or duplicate card ID")
        continue
      }
      let overBudget = metadata.sources.count > budget.maximumSourcesPerCard
      truncated = truncated || overBudget
      let sources = metadata.sources.prefix(budget.maximumSourcesPerCard).map {
        sourceState($0, repository: repository, maximumBytes: budget.maximumSourceBytes)
      }.sorted { $0.path < $1.path }
      let status: String
      if sources.contains(where: { $0.status == "changed" || $0.status == "missing" }) { status = "stale" }
      else if overBudget || sources.isEmpty || sources.contains(where: { $0.status != "matching" }) { status = "unverified" }
      else { status = "source-current" }
      let summary = markdown.components(separatedBy: "\n\n").dropFirst()
        .first { !$0.trimmingCharacters(in: .whitespacesAndNewlines).hasPrefix("#") }
        .map { String($0.prefix(500)) } ?? "Read the authored module card."
      cards.append(CardState(id: metadata.id, title: String(metadata.title.prefix(120)),
        file: file.path, summary: summary, status: status, sources: sources))
      cardURLs.append(file)
    }

    var index = """
      \(indexMarker)
      # Architecture context

      Read this index before opening the relevant module card. Source checksums detect drift; authored summaries remain semantically unverified. Stale or unverified cards require source inspection before relying on them.

      Budget: \(budget.maximumCards) cards, \(budget.maximumSourcesPerCard) references/card, \(budget.maximumIndexBytes) index bytes. This operation invokes no model, API, or provider.

      """
    if cards.isEmpty { index += "No authored cards found. See the architecture card format in the repository documentation.\n" }
    for card in cards {
      let url = URL(fileURLWithPath: card.file)
      let entry = "\n## [\(escapeLabel(card.title))](\(url.absoluteString))\n\nStatus: **\(card.status)**. Summary semantics: unverified.\n\n\(card.summary)\n\n"
        + card.sources.map { source in
          let url = repository.appendingPathComponent(source.path)
          return "- [\(escapeLabel(source.path))](\(url.absoluteString)): \(source.status); SHA256 \(source.currentSHA256.map { String($0.prefix(12)) } ?? "unavailable")\n"
        }.joined()
      guard index.utf8.count + entry.utf8.count + 150 <= budget.maximumIndexBytes else {
        truncated = true
        continue
      }
      index += entry
    }
    if truncated { index += "\nBudget reached. Consult the state JSON and authored cards for omitted context.\n" }
    let state = State(generator: generator, repositoryRoot: repository.path,
      semanticVerification: "unverified", budget: budget, truncated: truncated,
      skipped: Array(skipped.prefix(64)), cards: cards)
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    let stateData = try encoder.encode(state)
    try files.createDirectory(at: output, withIntermediateDirectories: true)
    try Data(index.utf8).write(to: indexURL, options: .atomic)
    try stateData.write(to: stateURL, options: .atomic)
    return ArchitectureContextReport(indexURL: indexURL, stateURL: stateURL, cardURLs: cardURLs,
      cardCount: cards.count, sourceCount: cards.reduce(0) { $0 + $1.sources.count }, truncated: truncated)
  }

  private static func sourceState(_ source: Source, repository: URL, maximumBytes: Int) -> SourceState {
    let path = source.path
    let components = path.split(separator: "/").map(String.init)
    let baseline = source.sha256?.lowercased()
    let url = repository.appendingPathComponent(path)
    let allowed = !path.hasPrefix("/") && allowedComponents(components)
      && sourceExtensions.contains(url.pathExtension.lowercased())
    guard allowed, safeDescendant(url, of: repository, allowMissing: true) else {
      return SourceState(path: path, baselineSHA256: baseline, currentSHA256: nil, status: "excluded")
    }
    guard FileManager.default.fileExists(atPath: url.path) else {
      return SourceState(path: path, baselineSHA256: baseline, currentSHA256: nil, status: "missing")
    }
    guard let data = boundedData(url, maximumBytes: maximumBytes) else {
      return SourceState(path: path, baselineSHA256: baseline, currentSHA256: nil, status: "unverified")
    }
    let current = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    let validBaseline = baseline?.range(of: #"^[a-f0-9]{64}$"#, options: .regularExpression) != nil
    return SourceState(path: path, baselineSHA256: baseline, currentSHA256: current,
      status: !validBaseline ? "unverified" : baseline == current ? "matching" : "changed")
  }

  private static func safeDescendant(_ url: URL, of root: URL, allowMissing: Bool = false) -> Bool {
    let rootParts = root.pathComponents
    let parts = url.standardizedFileURL.pathComponents
    guard parts.starts(with: rootParts), parts.count > rootParts.count else { return false }
    var current = root
    for part in parts.dropFirst(rootParts.count) {
      current.appendPathComponent(part)
      guard let attributes = try? FileManager.default.attributesOfItem(atPath: current.path) else { return allowMissing }
      if attributes[.type] as? FileAttributeType == .typeSymbolicLink { return false }
    }
    return true
  }

  private static func allowedComponents(_ components: [String]) -> Bool {
    !components.isEmpty && components.allSatisfy {
      !$0.hasPrefix(".") && !excluded.contains($0.lowercased())
        && !$0.lowercased().contains("secret") && !$0.lowercased().contains("credential")
        && !$0.lowercased().contains(".generated.")
    }
  }

  private static func isDirectory(_ url: URL) -> Bool {
    (try? FileManager.default.attributesOfItem(atPath: url.path)[.type] as? FileAttributeType) == .typeDirectory
  }

  private static func boundedData(_ url: URL, maximumBytes: Int) -> Data? {
    guard let attributes = try? FileManager.default.attributesOfItem(atPath: url.path),
      attributes[.type] as? FileAttributeType == .typeRegular,
      let size = attributes[.size] as? NSNumber, size.intValue <= maximumBytes,
      let handle = try? FileHandle(forReadingFrom: url) else { return nil }
    defer { try? handle.close() }
    do {
      let data = try handle.read(upToCount: maximumBytes + 1) ?? Data()
      return data.count <= maximumBytes ? data : nil
    } catch { return nil }
  }

  private static func validateOutput(_ url: URL, isIndex: Bool) throws {
    guard (try? FileManager.default.attributesOfItem(atPath: url.path)) != nil else { return }
    guard let data = boundedData(url, maximumBytes: 4_194_304) else { throw ArchitectureContextError.outputConflict(url.path) }
    if isIndex {
      guard String(data: data, encoding: .utf8)?.hasPrefix(indexMarker) == true else {
        throw ArchitectureContextError.outputConflict(url.path)
      }
    } else {
      guard let state = try? JSONDecoder().decode(State.self, from: data), state.generator == generator else {
        throw ArchitectureContextError.outputConflict(url.path)
      }
    }
  }

  private static func escapeLabel(_ text: String) -> String {
    text.replacingOccurrences(of: "[", with: "\\[").replacingOccurrences(of: "]", with: "\\]")
      .replacingOccurrences(of: "\n", with: " ")
  }
}
