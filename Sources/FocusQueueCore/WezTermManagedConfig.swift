import Foundation

/// The configuration file for WezTerm windows that Focus Queue starts in a new
/// WezTerm process.
///
/// `--skip-config` kept those windows on WezTerm's defaults, because a user
/// `gui-startup` handler that spawns its own window drops the `start` command
/// and would open a plain shell instead of the tmux attach. This file registers
/// a `gui-startup` handler first, which runs the requested command, applies the
/// task labels, and returns false so later handlers are skipped. It then loads
/// the user's own configuration, so fonts, colors, and key bindings still apply.
public enum WezTermManagedConfig {
  public static let tabTitleVariable = "FOCUS_QUEUE_WEZTERM_TAB_TITLE"
  public static let windowTitleVariable = "FOCUS_QUEUE_WEZTERM_WINDOW_TITLE"

  public struct Titles: Equatable, Sendable {
    public var tab: String
    public var window: String

    public init(tab: String, window: String) {
      self.tab = tab
      self.window = window
    }
  }

  public static func fileURL(supportDirectory: URL) -> URL {
    supportDirectory.appendingPathComponent("terminal/wezterm-managed.lua")
  }

  /// Writes the file when missing or outdated and returns its location.
  @discardableResult
  public static func install(supportDirectory: URL) throws -> URL {
    let url = fileURL(supportDirectory: supportDirectory)
    try FileManager.default.createDirectory(
      at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    let data = Data(script.utf8)
    if (try? Data(contentsOf: url)) != data { try data.write(to: url, options: .atomic) }
    return url
  }

  /// `open` arguments that start a new WezTerm process running `command`.
  /// Titles travel as environment variables because `wezterm start` has no
  /// title option and the new process has its own mux socket.
  public static func openArguments(
    applicationName: String, configFile: URL, titles: Titles?,
    directory: String?, command: [String]
  ) -> [String] {
    var arguments = ["-na", applicationName]
    if let titles {
      arguments += ["--env", "\(tabTitleVariable)=\(titles.tab)",
        "--env", "\(windowTitleVariable)=\(titles.window)"]
    }
    arguments += ["--args", "--config-file", configFile.path, "start", "--always-new-process"]
    if let directory { arguments += ["--cwd", directory] }
    return arguments + ["--"] + command
  }

  static let script = """
    -- Generated by ECC Focus Queue for the WezTerm windows it opens. Focus Queue
    -- rewrites this file, so change your own WezTerm configuration instead.
    local wezterm = require("wezterm")

    -- Registered before your configuration loads, so it runs first. Returning
    -- false skips later gui-startup handlers, which often spawn a default window
    -- and would drop the tmux attach command this window was opened for.
    wezterm.on("gui-startup", function(cmd)
      local tab, _, window = wezterm.mux.spawn_window(cmd or {})
      local tab_title = os.getenv("\(tabTitleVariable)")
      if tab_title ~= nil and tab_title ~= "" then
        tab:set_title(tab_title)
      end
      local window_title = os.getenv("\(windowTitleVariable)")
      if window_title ~= nil and window_title ~= "" then
        window:set_title(window_title)
      end
      return false
    end)

    -- Same search order WezTerm uses when no --config-file is given.
    local home = os.getenv("HOME") or ""
    local xdg = os.getenv("XDG_CONFIG_HOME")
    local candidates = {
      os.getenv("WEZTERM_CONFIG_FILE"),
      xdg and (xdg .. "/wezterm/wezterm.lua") or nil,
      home .. "/.config/wezterm/wezterm.lua",
      home .. "/.wezterm.lua",
    }

    local function readable(path)
      if path == nil or path == "" or path == wezterm.config_file then
        return false
      end
      local file = io.open(path, "r")
      if file == nil then
        return false
      end
      file:close()
      return true
    end

    for index = 1, 4 do
      local path = candidates[index]
      if readable(path) then
        local directory = path:match("^(.*)/[^/]*$")
        if directory ~= nil then
          package.path = directory .. "/?.lua;" .. directory .. "/?/init.lua;" .. package.path
        end
        local ok, config = pcall(dofile, path)
        if ok and config ~= nil then
          return config
        end
        wezterm.log_error("Focus Queue could not load " .. path .. ": " .. tostring(config))
        return {}
      end
    end
    return {}

    """
}
