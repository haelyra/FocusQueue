import importlib.util
import io
import json
import os
from pathlib import Path
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout


ROOT = Path(__file__).parents[1]


def load(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / "Scripts" / file)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FQ = load("focus_queue_fq", "focus_queue_fq.py")


class FqTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="fq test ")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.support = self.root / "support"
        (self.support / "shell").mkdir(parents=True)
        (self.support / "tasks" / "ECC-214").mkdir(parents=True)
        self.ledger = self.root / "ledger.sqlite"
        (self.root / "config.json").write_text(json.dumps({"focusQueueProjects": [
            {"id": "ecc", "name": "ECC", "taskPrefix": "ECC", "repositoryPath": ""}]}))
        (self.support / "shell" / "codex.zsh").write_text(
            "# Generated by ECC Focus Queue; the earlier alias stays in .zshrc for recovery.\n"
            "unalias codex 2>/dev/null || true\n"
            "function codex {\n  /usr/bin/python3 '"
            + str(self.support / "shell" / "focus_queue_codex_entry.py")
            + "' --usage-wrapper /wrappers/codex-wrapper --default-flag=--yolo -- \"$@\"\n}\n")
        self.environment = {"FOCUS_QUEUE_SUPPORT_DIR": str(self.support),
                            "FOCUS_QUEUE_PLACEMENT_CONFIG": str(self.root / "config.json"),
                            "FOCUS_QUEUE_PLACEMENT_LEDGER": str(self.ledger)}

    def run_main(self, argv):
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            code = FQ.main(argv)
        return code, stdout.getvalue(), stderr.getvalue()

    def test_help_and_provider_validation(self):
        code, stdout, _ = self.run_main(["--help"])
        self.assertEqual(code, 0)
        self.assertIn("fq <codex|claude>", stdout)
        code, _, stderr = self.run_main([])
        self.assertEqual(code, 2)
        code, _, stderr = self.run_main(["kimi"])
        self.assertEqual(code, 2)
        self.assertIn("choose a provider", stderr)

    def test_placed_dispatch_forces_task_and_preserves_arguments(self):
        captured = []
        stderr = io.StringIO()
        with redirect_stderr(stderr):
            code = FQ.main(["codex", "fix ECC-214 pane layout"], environment=dict(self.environment),
                           execv=lambda executable, command: captured.append(command))
        self.assertEqual(code, 0)
        command = captured[0]
        self.assertEqual(command[0], "/usr/bin/python3")
        self.assertTrue(command[1].endswith("focus_queue_codex_entry.py"))
        self.assertEqual(command[2:5], ["--usage-wrapper", "/wrappers/codex-wrapper",
                                        "--default-flag=--yolo"])
        self.assertEqual(command[command.index("--") + 1:], ["fix ECC-214 pane layout"])

    def test_placed_dispatch_sets_task_environment(self):
        environment = dict(self.environment)
        with redirect_stderr(io.StringIO()) as stderr:
            FQ.main(["codex", "fix ECC-214 pane layout"], environment=environment,
                    execv=lambda executable, command: None)
        self.assertEqual(environment["FOCUS_QUEUE_TASK_ID"], "ECC-214")
        self.assertIn("[fq] placed → ECC-214 (heuristic: prompt-ticket)", stderr.getvalue())

    def test_unplaced_dispatch_passes_through_unchanged(self):
        environment = dict(self.environment)
        captured = []
        with redirect_stderr(io.StringIO()) as stderr:
            FQ.main(["codex", "--cd", str(self.root), "hello"], environment=environment,
                    execv=lambda executable, command: captured.append(command))
        self.assertNotIn("FOCUS_QUEUE_TASK_ID", environment)
        self.assertIn("[fq] unplaced (no-signal) — launching untracked-by-task",
                      stderr.getvalue())
        command = captured[0]
        self.assertEqual(command[command.index("--") + 1:],
                         ["--cd", str(self.root), "hello"])

    def test_usage_wrapper_falls_back_to_environment(self):
        (self.support / "shell" / "codex.zsh").unlink()
        environment = dict(self.environment, FOCUS_QUEUE_CODEX_USAGE_WRAPPER="/alt/codex")
        captured = []
        with redirect_stderr(io.StringIO()):
            FQ.main(["codex", "hello"], environment=environment,
                    execv=lambda executable, command: captured.append(command))
        command = captured[0]
        self.assertEqual(command[2:4], ["--usage-wrapper", "/alt/codex"])


if __name__ == "__main__":
    unittest.main()
