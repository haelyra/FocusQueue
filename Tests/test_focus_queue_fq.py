import importlib.util
import io
import json
import os
from pathlib import Path
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout


ROOT = Path(__file__).parents[1]


def load(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / "Scripts" / file)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FQ = load("focus_queue_fq", "focus_queue_fq.py")


class FqTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="fq test ")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.support = self.root / "support"
        (self.support / "shell").mkdir(parents=True)
        (self.support / "tasks" / "ECC-214").mkdir(parents=True)
        self.ledger = self.root / "ledger.sqlite"
        (self.root / "config.json").write_text(json.dumps({"placementModelEnabled": False,
                                                           "focusQueueProjects": [
            {"id": "ecc", "name": "ECC", "taskPrefix": "ECC", "repositoryPath": ""}]}))
        (self.support / "shell" / "codex.zsh").write_text(
            "# Generated by ECC Focus Queue; the earlier alias stays in .zshrc for recovery.\n"
            "unalias codex 2>/dev/null || true\n"
            "function codex {\n  /usr/bin/python3 '"
            + str(self.support / "shell" / "focus_queue_codex_entry.py")
            + "' --usage-wrapper /wrappers/codex-wrapper --default-flag=--yolo -- \"$@\"\n}\n")
        self.environment = {"FOCUS_QUEUE_SUPPORT_DIR": str(self.support),
                            "FOCUS_QUEUE_PLACEMENT_CONFIG": str(self.root / "config.json"),
                            "FOCUS_QUEUE_PLACEMENT_LEDGER": str(self.ledger)}

    def run_main(self, argv):
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            code = FQ.main(argv)
        return code, stdout.getvalue(), stderr.getvalue()

    def test_help_and_provider_validation(self):
        code, stdout, _ = self.run_main(["--help"])
        self.assertEqual(code, 0)
        self.assertIn("fq <codex|claude>", stdout)
        code, _, stderr = self.run_main([])
        self.assertEqual(code, 2)
        code, _, stderr = self.run_main(["kimi"])
        self.assertEqual(code, 2)
        self.assertIn("choose a provider", stderr)

    def test_placed_dispatch_forces_task_and_preserves_arguments(self):
        captured = []
        stderr = io.StringIO()
        with redirect_stderr(stderr):
            code = FQ.main(["codex", "fix ECC-214 pane layout"], environment=dict(self.environment),
                           execv=lambda executable, command: captured.append(command))
        self.assertEqual(code, 0)
        command = captured[0]
        self.assertEqual(command[0], "/usr/bin/python3")
        self.assertTrue(command[1].endswith("focus_queue_codex_entry.py"))
        self.assertEqual(command[2:5], ["--usage-wrapper", "/wrappers/codex-wrapper",
                                        "--default-flag=--yolo"])
        self.assertEqual(command[command.index("--") + 1:], ["fix ECC-214 pane layout"])

    def test_placed_dispatch_sets_task_environment(self):
        environment = dict(self.environment)
        with redirect_stderr(io.StringIO()) as stderr:
            FQ.main(["codex", "fix ECC-214 pane layout"], environment=environment,
                    execv=lambda executable, command: None)
        self.assertEqual(environment["FOCUS_QUEUE_TASK_ID"], "ECC-214")
        self.assertIn("[fq] placed → ECC-214 (heuristic: prompt-ticket)", stderr.getvalue())

    def test_unplaced_dispatch_passes_through_unchanged(self):
        environment = dict(self.environment)
        captured = []
        with redirect_stderr(io.StringIO()) as stderr:
            FQ.main(["codex", "--cd", str(self.root), "hello"], environment=environment,
                    execv=lambda executable, command: captured.append(command))
        self.assertNotIn("FOCUS_QUEUE_TASK_ID", environment)
        self.assertIn("[fq] unplaced (no-signal) — launching untracked-by-task",
                      stderr.getvalue())
        command = captured[0]
        self.assertEqual(command[command.index("--") + 1:],
                         ["--cd", str(self.root), "hello"])

    def test_usage_wrapper_falls_back_to_environment(self):
        (self.support / "shell" / "codex.zsh").unlink()
        environment = dict(self.environment, FOCUS_QUEUE_CODEX_USAGE_WRAPPER="/alt/codex")
        captured = []
        with redirect_stderr(io.StringIO()):
            FQ.main(["codex", "hello"], environment=environment,
                    execv=lambda executable, command: captured.append(command))
        command = captured[0]
        self.assertEqual(command[2:4], ["--usage-wrapper", "/alt/codex"])


def executable(path, body):
    path.write_text(f"#!{sys.executable}\nimport json, sys\n{body}")
    path.chmod(0o755)
    return path


class FqModelPlacementTests(unittest.TestCase):
    """fq with the model backend on, using a fake Claude CLI and a fake helper."""

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="fq model test ")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.support = self.root / "support"
        self.support.mkdir()
        dashboard = self.root / "dashboard.json"
        dashboard.write_text(json.dumps({"tickets": [
            {"id": "ECC-018", "title": "Fix tmux clipboard sync", "status": "in-progress"}]}))
        (self.root / "config.json").write_text(json.dumps({"focusQueueProjects": [
            {"id": "ecc", "name": "ECC", "taskPrefix": "ECC", "repositoryPath": "",
             "dashboardPath": str(dashboard)}]}))
        self.helper_log = self.root / "helper.jsonl"
        self.environment = {
            "FOCUS_QUEUE_SUPPORT_DIR": str(self.support),
            "FOCUS_QUEUE_PLACEMENT_CONFIG": str(self.root / "config.json"),
            "FOCUS_QUEUE_PLACEMENT_LEDGER": str(self.root / "ledger.sqlite"),
            "FOCUS_QUEUE_CLAUDE_USAGE_WRAPPER": "/alt/claude",
            "FOCUS_QUEUE_PLACEMENT_CLAUDE_EXECUTABLE": str(self.root / "claude"),
            "FOCUS_QUEUE_SESSION_HELPER": str(self.root / "focus-queue-session"),
            "FOCUS_QUEUE_SUBTASK_ID": "parent-agent",
            "CLAUDE_CODE_SESSION_ID": "parent-session",
        }
        self.helper()

    def reply(self, task_id, confidence, title="Write the release notes"):
        envelope = {"is_error": False, "structured_output": {
            "taskID": task_id, "confidence": confidence, "title": title, "reason": "r"}}
        executable(self.root / "claude", f"sys.stdin.read()\nprint({json.dumps(envelope)!r})\n")

    def helper(self, *, fail=()):
        executable(self.root / "focus-queue-session", (
            "import os\n"
            f"open({str(self.helper_log)!r}, 'a').write(json.dumps({{'argv': sys.argv[1:], "
            "'env': {k: v for k, v in os.environ.items() if k.startswith(('FOCUS_QUEUE_', 'CLAUDE_'))}})"
            " + '\\n')\n"
            f"if sys.argv[1] in {list(fail)!r}:\n"
            "    sys.stderr.write('simulated failure'); sys.exit(1)\n"
            "if sys.argv[1] == 'placement':\n"
            "    print(json.dumps({'status': 'placed', 'taskID': 'ECC-031', 'launchID': sys.argv[3]}))\n"
            "else:\n"
            "    print(json.dumps({'updated': sys.argv[3]}))\n"))

    def helper_calls(self):
        if not self.helper_log.exists():
            return []
        return [json.loads(line) for line in self.helper_log.read_text().splitlines()]

    def dispatch(self, prompt):
        environment = dict(self.environment)
        captured = []
        with redirect_stderr(io.StringIO()) as stderr:
            code = FQ.main(["claude", prompt], environment=environment,
                           execv=lambda executable, command: captured.append(command))
        self.assertEqual(code, 0)
        self.assertEqual(captured[0][captured[0].index("--") + 1:], [prompt])
        return environment, stderr.getvalue()

    def test_confident_match_places_the_existing_task(self):
        self.reply("ECC-018", 0.9)
        environment, stderr = self.dispatch("tmux copy broke again")
        self.assertEqual(environment["FOCUS_QUEUE_TASK_ID"], "ECC-018")
        self.assertIn("[fq] placing with claude/haiku against 1 open tasks…", stderr)
        self.assertIn("[fq] placed → ECC-018 (claude/haiku: model-match, confidence 0.90)", stderr)
        self.assertEqual(self.helper_calls(), [], "Joining a task creates nothing")

    def test_new_work_creates_and_titles_a_task_before_launch(self):
        self.reply(None, 0)
        environment, stderr = self.dispatch("draft release notes for 2.3")
        self.assertEqual(environment["FOCUS_QUEUE_TASK_ID"], "ECC-031")
        self.assertIn("[fq] created → ECC-031 “Write the release notes” (claude/haiku: model-new", stderr)
        placement, rename = self.helper_calls()
        self.assertEqual(placement["argv"][0], "placement")
        self.assertEqual(placement["argv"][placement["argv"].index("--prompt") + 1],
                         "draft release notes for 2.3")
        self.assertEqual(placement["argv"][placement["argv"].index("--cwd") + 1], os.getcwd())
        self.assertEqual(placement["env"]["FOCUS_QUEUE_PROVIDER"], "claude")
        for inherited in ("FOCUS_QUEUE_SUBTASK_ID", "CLAUDE_CODE_SESSION_ID", "FOCUS_QUEUE_TASK_ID"):
            self.assertNotIn(inherited, placement["env"])
        self.assertEqual(rename["argv"], ["task", "rename", "ECC-031", "Write the release notes"])

    def test_low_confidence_match_still_creates_a_new_task(self):
        self.reply("ECC-018", 0.3)
        environment, stderr = self.dispatch("something about copying")
        self.assertEqual(environment["FOCUS_QUEUE_TASK_ID"], "ECC-031")

    def test_creation_failure_launches_without_a_task(self):
        self.reply(None, 0)
        self.helper(fail=("placement",))
        environment, stderr = self.dispatch("draft release notes")
        self.assertNotIn("FOCUS_QUEUE_TASK_ID", environment)
        self.assertIn("[fq] could not create a task (focus-queue-session placement failed: "
                      "simulated failure)", stderr)

    def test_rename_failure_keeps_the_created_task(self):
        self.reply(None, 0)
        self.helper(fail=("task",))
        environment, stderr = self.dispatch("draft release notes")
        self.assertEqual(environment["FOCUS_QUEUE_TASK_ID"], "ECC-031")
        self.assertIn("[fq] kept the prompt-derived title for ECC-031", stderr)

    def test_model_failure_falls_back_to_phase_one_behavior(self):
        executable(self.root / "claude", "sys.exit(7)\n")
        environment, stderr = self.dispatch("draft release notes")
        self.assertNotIn("FOCUS_QUEUE_TASK_ID", environment)
        self.assertIn("[fq] model placement unavailable (claude exited 7", stderr)
        self.assertIn("[fq] unplaced (unmapped-repo)", stderr)
        self.assertEqual(self.helper_calls(), [])


if __name__ == "__main__":
    unittest.main()
